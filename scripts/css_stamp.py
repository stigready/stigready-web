#!/usr/bin/env python3
"""The fingerprint that ties assets/css/site.css to the build that produced it (claude-agents#152).

site.css is generated by scripts/build-css.sh (Tailwind CLI, pinned) from the classes on every page. The Cairn runners
have no Node and no npm registry on their egress allowlist, so the gate cannot re-run Tailwind. Instead build-css.sh
records, next to the CSS, everything the CSS is a function of: the CLI version, tailwind.config.js, the input CSS, the
set of class tokens on the pages, and the CSS's own sha256. validate-site.py recomputes it and fails when any of them
changed since the last build: a class added to a page without a rebuild, an edited config, or a hand-edited site.css.

Copy-only edits do not change the class set, so they need no rebuild.

  css_stamp.py --write    (build-css.sh runs this after Tailwind)
  css_stamp.py --check    (exit 1 and print what changed)
"""
from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CSS = ROOT / "assets" / "css" / "site.css"
STAMP = ROOT / "assets" / "css" / "site.css.stamp.json"
CONFIG = ROOT / "tailwind.config.js"
INPUT = ROOT / "assets" / "css" / "tailwind.input.css"
BUILD = ROOT / "scripts" / "build-css.sh"
# tailwind.config.js `content`: the pages Tailwind scans.
PAGE_GLOBS = ("*.html", "applied/*.html", "blog/*.html")

CLASS_ATTR = re.compile(r"""\bclass\s*=\s*(?:"([^"]*)"|'([^']*)')""")
CLASS_LIST = re.compile(r"""classList\.(?:add|remove|toggle)\(\s*(['"])([^'"]+)\1""")


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def cli_version() -> str:
    m = re.search(r"tailwindcss@(\d+\.\d+\.\d+)", BUILD.read_text())
    return m.group(1) if m else ""


def class_tokens() -> list[str]:
    """Every token in a class attribute or a classList call on the pages Tailwind scans."""
    tokens: set[str] = set()
    for glob in PAGE_GLOBS:
        for page in sorted(ROOT.glob(glob)):
            text = page.read_text(encoding="utf-8", errors="ignore")
            for m in CLASS_ATTR.finditer(text):
                tokens.update((m.group(1) if m.group(1) is not None else m.group(2)).split())
            for m in CLASS_LIST.finditer(text):
                tokens.update(m.group(2).split())
    return sorted(tokens)


def compute() -> dict:
    toks = class_tokens()
    return {
        "tailwindcss": cli_version(),
        "config_sha256": sha(CONFIG.read_bytes()),
        "input_sha256": sha(INPUT.read_bytes()),
        "class_tokens": len(toks),
        "class_tokens_sha256": sha("\n".join(toks).encode()),
        "site_css_sha256": sha(CSS.read_bytes()) if CSS.is_file() else None,
    }


def problems() -> list[str]:
    if not STAMP.is_file():
        return [f"{STAMP.relative_to(ROOT)} is missing: run scripts/build-css.sh"]
    try:
        want = json.loads(STAMP.read_text())
    except json.JSONDecodeError as e:
        return [f"{STAMP.relative_to(ROOT)}: invalid JSON ({e}): run scripts/build-css.sh"]
    got = compute()
    why = {
        "tailwindcss": "the Tailwind CLI version in scripts/build-css.sh changed",
        "config_sha256": "tailwind.config.js changed",
        "input_sha256": "assets/css/tailwind.input.css changed",
        "class_tokens_sha256": "the classes on the pages changed",
        "site_css_sha256": "assets/css/site.css is not the file scripts/build-css.sh wrote",
    }
    return [f"site.css is stale: {msg} since the last build; run scripts/build-css.sh and commit both files"
            for key, msg in why.items() if want.get(key) != got[key]]


def main(argv: list[str]) -> int:
    if argv == ["--write"]:
        STAMP.write_text(json.dumps(compute(), indent=2) + "\n")
        print(f"wrote {STAMP.relative_to(ROOT)}")
        return 0
    if argv == ["--check"]:
        found = problems()
        for p in found:
            print(f"FAIL {p}", file=sys.stderr)
        return 1 if found else 0
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
