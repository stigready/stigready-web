"""The fingerprint that ties assets/css/site.css to the build that produced it (claude-agents#152).

site.css is generated by scripts/build-css.sh (Tailwind CLI, pinned) from the classes on every page. The Cairn runners
have no Node and no npm registry on their egress allowlist, so the gate cannot re-run Tailwind. Instead build-css.sh
records, next to the CSS, everything the CSS is a function of: the CLI version, tailwind.config.js, the input CSS, the
set of class tokens on the pages, and the CSS's own sha256. The CINC control web-site-css-fresh
(cinc/profiles/stigready-web/controls/css_fresh.rb) recomputes it and fails when any of them changed since the last
build: a class added to a page without a rebuild, an edited config, or a hand-edited site.css. This script only writes
the stamp (building); the assertion is CINC's (decision 0003). Change a field here and change it there.

Copy-only edits do not change the class set, so they need no rebuild.

  css_stamp.py --write    (build-css.sh runs this after Tailwind)
"""
from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CSS = ROOT / "assets" / "css" / "site.css"
STAMP = ROOT / "assets" / "css" / "site.css.stamp.json"
CONFIG = ROOT / "tailwind.config.js"
INPUT = ROOT / "assets" / "css" / "tailwind.input.css"
BUILD = ROOT / "scripts" / "build-css.sh"
# tailwind.config.js `content`: the pages Tailwind scans.
PAGE_GLOBS = ("*.html", "applied/*.html", "blog/*.html")

CLASS_ATTR = re.compile(r"""\bclass\s*=\s*(?:"([^"]*)"|'([^']*)')""")
CLASS_LIST = re.compile(r"""classList\.(?:add|remove|toggle)\(\s*(['"])([^'"]+)\1""")
# stigready-web#67: classes set in JS strings (a ternary, a variable, a template literal) are in no class attribute, so
# every word of every inline executable <script> counts as a token, split on whitespace and quotes. Tailwind scans the
# same text, so any script edit changes the fingerprint and needs a rebuild; copy outside scripts still does not.
SCRIPT_ELEMENT = re.compile(r"""<script\b((?:[^>"']|"[^"]*"|'[^']*')*)>(.*?)</script\s*>""", re.S | re.I)
SCRIPT_SKIP = re.compile(r"""\bsrc\s*=|\btype\s*=\s*["']?application/(?:ld\+)?json""", re.I)
SCRIPT_SPLIT = re.compile(r"""[ \t\n\r\f\v'"`]+""")  # ASCII whitespace only, as Ruby's
VERSION = re.compile(r"^TAILWIND_VERSION=(\d+\.\d+\.\d+)$", re.M)


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def cli_version() -> str:
    m = VERSION.search(BUILD.read_text())
    return m.group(1) if m else ""


def class_tokens() -> list[str]:
    """Every token in a class attribute, a classList call or an inline script on the pages Tailwind scans."""
    tokens: set[str] = set()
    for glob in PAGE_GLOBS:
        for page in sorted(ROOT.glob(glob)):
            text = page.read_text(encoding="utf-8", errors="ignore")
            for m in CLASS_ATTR.finditer(text):
                tokens.update((m.group(1) if m.group(1) is not None else m.group(2)).split())
            for m in CLASS_LIST.finditer(text):
                tokens.update(m.group(2).split())
            for attrs, script in SCRIPT_ELEMENT.findall(text):
                if not SCRIPT_SKIP.search(attrs):
                    tokens.update(t for t in SCRIPT_SPLIT.split(script) if t)
    return sorted(tokens)


def compute() -> dict:
    toks = class_tokens()
    return {
        "tailwindcss": cli_version(),
        "config_sha256": sha(CONFIG.read_bytes()),
        "input_sha256": sha(INPUT.read_bytes()),
        "class_tokens": len(toks),
        "class_tokens_sha256": sha("\n".join(toks).encode()),
        "site_css_sha256": sha(CSS.read_bytes()) if CSS.is_file() else None,
    }


def main(argv: list[str]) -> int:
    if argv == ["--write"]:
        STAMP.write_text(json.dumps(compute(), indent=2) + "\n")
        print(f"wrote {STAMP.relative_to(ROOT)}")
        return 0
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
